function prefixMenuVisibilityItems<Items extends Record<string, string>>(
  items: Items
) {
  return Object.fromEntries(
    Object.entries(items).map(([id, label]) => [
      `menuVisibilityItem-${id}`,
      label,
    ])
  ) as {
    [Key in keyof Items as `menuVisibilityItem-${Key & string}`]: Items[Key]
  }
}

